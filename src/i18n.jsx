export function IdiomaProvider({ children }) {
  const [idioma, setIdioma] = useState(() => localStorage.getItem('cryptonguard-idioma') || 'es');

  useEffect(() => {
    localStorage.setItem('cryptonguard-idioma', idioma);
    document.documentElement.lang = idioma;
    document.title = idioma === 'en'
      ? 'Cryptonguard | Crypto Seller Reviews'
      : 'Cryptonguard | Reseñas de vendedores crypto';
  }, [idioma]);

  const t = (texto, valores = {}) => {
    const traducido = idioma === 'en' ? (traducciones[texto] || texto) : texto;
    return Object.entries(valores).reduce(
      (resultado, [clave, valor]) => resultado.replace(`{${clave}}`, valor),
      traducido,
    );
  };

  return (
    <IdiomaContexto.Provider value={{ idioma, setIdioma, t }}>
      {children}
    </IdiomaContexto.Provider>
  );
}
